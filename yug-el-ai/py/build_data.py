"""
build_data.py
-------------
Runs the smart layer and writes ../js/data_generated.js, which the web app
loads BEFORE js/data.js. Produces:
  - DRAINS_MAJOR : the trimmed ~360-segment drainage network (declutter)
  - FLOOD_MODEL  : trained logistic-regression weights (smart risk scoring)
  - GEN_META     : provenance / counts

Run:  python build_data.py
"""
from __future__ import annotations
import os, json, datetime
from drainage_network import build_major_drains
from flood_risk_model import train_model

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "js", "data_generated.js"))


def js_array_of_drains(drains):
    rows = []
    for s in drains:
        a, b = s["pts"]
        rows.append(
            '{pts:[[%s,%s],[%s,%s]],order:%d,valley:"%s",kind:"%s"}'
            % (a[0], a[1], b[0], b[1], s["order"], s["valley"], s["kind"])
        )
    return "[\n" + ",\n".join(rows) + "\n]"


def main(target=360):
    drains, total = build_major_drains(target=target)
    model = train_model()
    meta = {
        "drains_major": len(drains),
        "drains_full": total,
        "model": model["kind"],
        "accuracy": model["accuracy"],
        "generated": datetime.datetime.now().isoformat(timespec="seconds"),
        "source": "DrainSight smart layer (py/build_data.py)",
    }

    header = (
        "/* ===================================================================\n"
        "   AUTO-GENERATED by py/build_data.py  -  DO NOT EDIT BY HAND\n"
        "   Re-run:  python py/build_data.py\n"
        f"   {meta['drains_full']} raw segments trimmed to {meta['drains_major']} major drains;\n"
        f"   flood model: {meta['model']} (train acc {meta['accuracy']}).\n"
        "   =================================================================== */\n"
    )
    body = (
        header
        + "const DRAINS_MAJOR = " + js_array_of_drains(drains) + ";\n\n"
        + "const FLOOD_MODEL = " + json.dumps(model) + ";\n\n"
        + "const GEN_META = " + json.dumps(meta) + ";\n"
    )
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"wrote {OUT}")
    print(f"  {meta['drains_major']} major drains, model={meta['model']} acc={meta['accuracy']}")


if __name__ == "__main__":
    main()
